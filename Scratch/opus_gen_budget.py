def check_numbers(moduli, two_unit):
    """Evaluate every closed inequality of the generated file in Python (the kernel re-checks them)."""
    M = math.prod(moduli)
    num = pad_num(moduli)
    numer = num + 637 * (2 ** 384 % P) * 2 ** 3968
    assert numer * 2 ** 100 * 1000 <= 2 ** 4352
    smudge = 1284 * (P - 1) ** 2 + 273 * P
    window = 15 * ((P - 1) ** 2 + 1)
    if two_unit:
        assert smudge * 2 ** 100 * 50 <= 77 * M
        assert window * 2 ** 100 * 50 <= M
    else:
        assert smudge * 2 ** 100 * 20 <= M
    assert 2 * ((P - 1) ** 2 + 1) <= M, 'wrap exactness needs 2B <= M'
    total = ((3 * numer * (M * P * (R - 1)) + ((smudge + window) if two_unit else smudge) * (2 ** 4352 * P * (R - 1))
              + 1759967 * (2 ** 4352 * M * (R - 1)) + (546 + 455) * (2 ** 4352 * M * P)
              + (185 + 1) * 2 ** 4224 * (M * P * (R - 1))) * 2 ** 100)
    D = 2 ** 4352 * M * P * (R - 1)
    assert total <= (2 if two_unit else 1) * D
    return total / D


def main():
    if sys.argv[1:2] == ['check']:
        pinned = subprocess.run(['git', '-C', str(ROOT), 'show',
                                 'e37c4db3cdbf11c741ff812ed1b0d5ae7c7b3b05:Proof/Privacy/CRT/Glue/BudgetData.lean'],
                                capture_output=True, text=True, check=True).stdout
        generated = generate(BASE, two_unit=False)
        print('legacy constant (units):', check_numbers(BASE, False))
        print('byte-identical to e37c4db:', generated == pinned)
        if generated != pinned:
            Path('/tmp/opus_budgetdata_legacy.lean').write_text(generated)
            sys.exit(1)
    elif sys.argv[1:2] == ['write']:
        moduli = [int(x) for x in sys.argv[2:]] or [m for m in BASE if m != 17]
        print('two-unit constant (units):', check_numbers(moduli, True))
        TARGET.write_text(generate(moduli, two_unit=True))
        print('wrote', TARGET)
    else:
        sys.exit(__doc__)


if __name__ == '__main__':
    main()
